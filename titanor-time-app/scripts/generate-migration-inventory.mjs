#!/usr/bin/env node
// R06-A — regenerate lib/generated/migration-inventory.ts from prisma/migrations/.
//
//   node scripts/generate-migration-inventory.mjs           # rewrite the file
//   node scripts/generate-migration-inventory.mjs --check    # exit 1 if out of sync (CI gate)
//
// The inventory is the exact set of migration directory names the CURRENT build expects the
// database to have fully applied. /api/ready and the scheduler compare it against
// _prisma_migrations — a strict set/state check, never "count == N".

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = join(HERE, '..', '..', 'prisma', 'migrations');
const OUT = join(HERE, '..', 'lib', 'generated', 'migration-inventory.ts');

const names = readdirSync(MIGRATIONS_DIR, { withFileTypes: true })
  .filter((e) => e.isDirectory() && /^\d{14}_/.test(e.name))
  .map((e) => e.name)
  .sort();

const checksum = createHash('sha256').update(names.join('\n')).digest('hex');

const body = `// GENERATED by scripts/generate-migration-inventory.mjs — do not edit by hand.
// Run \`npm run generate:migration-inventory\` after adding a migration. CI ( \`npm run lint\` /
// the R02 CI workflow) fails if this file drifts from prisma/migrations/.
//
// R06-A — the exact migration set this build expects the database to have fully applied.

export const MIGRATION_INVENTORY = [
${names.map((n) => `  '${n}'`).join(',\n')}
] as const;

export const MIGRATION_INVENTORY_COUNT = ${names.length};

/** sha256 of the newline-joined sorted names — a cheap single-value schema-version fingerprint. */
export const MIGRATION_INVENTORY_CHECKSUM = '${checksum}';

/** The newest migration this build knows about (informational only — comparisons use the full set). */
export const LATEST_KNOWN_MIGRATION = '${names[names.length - 1] ?? ''}';
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== body) {
    console.error('migration-inventory.ts is out of sync with prisma/migrations/ — run `npm run generate:migration-inventory` and commit.');
    process.exit(1);
  }
  console.log(`migration-inventory.ts: OK — ${names.length} migrations, checksum ${checksum.slice(0, 12)}…`);
  process.exit(0);
}

writeFileSync(OUT, body, 'utf8');
console.log(`wrote lib/generated/migration-inventory.ts — ${names.length} migrations, checksum ${checksum.slice(0, 12)}…`);
