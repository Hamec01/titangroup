export interface PageQueryInput {
  page: string | null;
  pageSize: string | null;
}

export type PageQueryResult = { ok: true; page: number; pageSize: number } | { ok: false; fieldErrors: Record<string, string[]> };

export function parsePageQuery(input: PageQueryInput): PageQueryResult {
  const fieldErrors: Record<string, string[]> = {};

  let page = 1;
  if (input.page !== null && input.page !== '') {
    const parsed = Number(input.page);
    if (!Number.isInteger(parsed) || parsed < 1) {
      fieldErrors.page = ['must be a positive integer'];
    } else {
      page = parsed;
    }
  }

  let pageSize = DEFAULT_PAGE_SIZE;
  if (input.pageSize !== null && input.pageSize !== '') {
    const parsed = Number(input.pageSize);
    if (!Number.isInteger(parsed) || parsed < 1 || parsed > MAX_PAGE_SIZE) {
      fieldErrors.pageSize = [`must be an integer between 1 and ${MAX_PAGE_SIZE}`];
    } else {
      pageSize = parsed;
    }
  }

  if (Object.keys(fieldErrors).length > 0) {
    return { ok: false, fieldErrors };
  }
  return { ok: true, page, pageSize };
}

export function isValidExportBatchId(batchId: string): boolean {
  return UUID_PATTERN.test(batchId);
}

export interface ExportBatchListResult {
  items: ExportBatchSummaryDto[];
  page: number;
  pageSize: number;
  totalItems: number;
  totalPages: number;
}

/** §BK GET /api/admin/export-batches — list, newest first, never includes `content`. */
export async function listExportBatches(filter: { periodId?: string }, pagination: { page: number; pageSize: number }): Promise<ExportBatchListResult> {
  const where = filter.periodId ? { periodId: filter.periodId } : {};
  const [totalItems, rows] = await Promise.all([
    prisma.exportBatch.count({ where }),
    prisma.exportBatch.findMany({
      where,
      orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
      skip: (pagination.page - 1) * pagination.pageSize,
      take: pagination.pageSize,
      select: EXPORT_BATCH_SUMMARY_SELECT
    })
  ]);
  return {
    items: rows.map(toSummaryDto),
    page: pagination.page,
    pageSize: pagination.pageSize,
    totalItems,
    totalPages: Math.ceil(totalItems / pagination.pageSize)
  };
}

