// ============================================================================
// §BF — POST /api/admin/periods/:periodId/export service.
// ============================================================================

export type CreateExportBatchError = { code: 'PERIOD_NOT_FOUND' } | { code: 'PERIOD_NOT_EXPORTABLE' } | { code: 'NOTHING_TO_EXPORT' };

export interface CreateExportBatchResult {
  batch: ExportBatchSummaryDto;
  period: { id: string; status: 'EXPORTED'; exportedAt: string };
  coveredCorrectionCount: number;
}

/**
 * §BF — one transaction. Lock order: PayrollPeriod -> Timesheet[] (ORDER BY id) -> (CORRECTION only)
 * CorrectionRequest[] (ORDER BY id) — §BM. Population (§BA) is exactly
 * PayrollPeriodParticipant.expected=true for this period, for both FULL and CORRECTION (a CORRECTION
 * batch is always a full replacement snapshot, never a delta, §BB). An expected participant without
 * a FINAL_APPROVED Timesheet + currentVersionId is an invariant failure (throw, never a silent skip
 * or partial batch) — period.lock already guarantees this for FULL, but this function re-verifies it
 * itself rather than trusting a fact proven at a different point in time (same TOCTOU-safe posture as
 * lib/periods.ts::lockPeriod's own re-check-under-the-lock).
 */
export async function createExportBatch(periodId: string, actorUserId: string, requestId: string): Promise<CreateExportBatchResult | CreateExportBatchError> {
  return prisma.$transaction(async (tx): Promise<CreateExportBatchResult | CreateExportBatchError> => {
    await tx.$queryRaw`SELECT id FROM "PayrollPeriod" WHERE id = ${periodId}::uuid FOR UPDATE`;
    const period = await tx.payrollPeriod.findUnique({ where: { id: periodId } });
    if (!period) {
      return { code: 'PERIOD_NOT_FOUND' };
    }
    if (period.status === 'OPEN') {
      return { code: 'PERIOD_NOT_EXPORTABLE' };
    }

    // §BA — population: exactly expected=true participants, for FULL and CORRECTION alike.
    const participants = await tx.payrollPeriodParticipant.findMany({ where: { periodId, expected: true }, select: { employeeId: true } });
    const expectedEmployeeIds = participants.map((p) => p.employeeId).sort();

    let kind: 'FULL' | 'CORRECTION';
    if (period.status === 'LOCKED') {
      kind = 'FULL';
    } else {
      // EXPORTED — §BC: eligibility is scoped to pending corrections belonging to expected
      // participants only (a correction on an excluded participant's timesheet can never be
      // represented in any snapshot, so it must never make a batch "needed" either).
      const pendingPeek = await tx.correctionRequest.count({
        where: { status: 'APPROVED', pendingExport: true, timesheet: { periodId, employeeId: { in: expectedEmployeeIds } } }
      });
      if (pendingPeek === 0) {
        return { code: 'NOTHING_TO_EXPORT' };
      }
      kind = 'CORRECTION';
    }

    // §BF step 3 / §BM — lock every expected participant's Timesheet row, ascending id, in one
    // statement (same idiom as lib/periods.ts::createPeriod's Employee lock).
    if (expectedEmployeeIds.length > 0) {
      await tx.$queryRaw`SELECT id FROM "Timesheet" WHERE "periodId" = ${periodId}::uuid AND "employeeId" = ANY(${expectedEmployeeIds}::uuid[]) ORDER BY id FOR UPDATE`;
    }
    const timesheets = await tx.timesheet.findMany({
      where: { periodId, employeeId: { in: expectedEmployeeIds } },
      select: { id: true, employeeId: true, status: true, currentVersionId: true }
    });
    const timesheetByEmployee = new Map(timesheets.map((t) => [t.employeeId, t]));
    for (const employeeId of expectedEmployeeIds) {
      const t = timesheetByEmployee.get(employeeId);
      if (!t || t.status !== 'FINAL_APPROVED' || !t.currentVersionId) {
        throw new Error(`EXPORT_INVARIANT_FAILURE: expected participant ${employeeId} lacks a FINAL_APPROVED timesheet with a currentVersionId (periodId=${periodId})`);
      }
    }

    // §BF step 4 / §BM — CORRECTION only: lock the eligible pending CorrectionRequest rows,
    // ascending id, then re-read their authoritative state under that lock (TOCTOU-safe, mirrors the
    // Timesheet re-check just above).
    let pendingCorrectionIds: string[] = [];
    if (kind === 'CORRECTION') {
      const candidateIds = (
        await tx.correctionRequest.findMany({
          where: { status: 'APPROVED', pendingExport: true, timesheet: { periodId, employeeId: { in: expectedEmployeeIds } } },
          select: { id: true },
          orderBy: { id: 'asc' }
        })
      ).map((c) => c.id);
      if (candidateIds.length > 0) {
        await tx.$queryRaw`SELECT id FROM "CorrectionRequest" WHERE id = ANY(${candidateIds}::uuid[]) ORDER BY id FOR UPDATE`;
      }
      const fresh = await tx.correctionRequest.findMany({
        where: { id: { in: candidateIds }, status: 'APPROVED', pendingExport: true },
        select: { id: true },
        orderBy: { id: 'asc' }
      });
      pendingCorrectionIds = fresh.map((c) => c.id);
      if (pendingCorrectionIds.length === 0) {
        return { code: 'NOTHING_TO_EXPORT' };
      }
    }

    // §BF step 6 — bulk, set-based reads. Zero queries inside any per-worker/per-day loop.
    const versionIds = timesheets.map((t) => t.currentVersionId!);
    const versionIdToEmployeeId = new Map(timesheets.map((t) => [t.currentVersionId!, t.employeeId]));

    const [employees, segments] = await Promise.all([
      expectedEmployeeIds.length > 0
        ? tx.employee.findMany({ where: { id: { in: expectedEmployeeIds } }, select: { id: true, employeeNumber: true, firstName: true, lastName: true } })
        : Promise.resolve([]),
      versionIds.length > 0
        ? tx.workSegment.findMany({
            where: { timesheetVersionId: { in: versionIds } },
            select: { timesheetVersionId: true, siteId: true, date: true, startAt: true, endAt: true, breaks: { select: { startAt: true, endAt: true, paid: true } } }
          })
        : Promise.resolve([])
    ]);
    const employeeById = new Map(employees.map((e) => [e.id, e]));

    // §BD — canonical (employeeId, siteId, date) bucket, shared with T8.3.
    const bucketInputs: CanonicalDailyBucketSegmentInput[] = segments.map((s) => ({
      employeeId: versionIdToEmployeeId.get(s.timesheetVersionId)!,
      timesheetVersionId: s.timesheetVersionId,
      siteId: s.siteId,
      date: s.date,
      startAt: s.startAt,
      endAt: s.endAt,
      breaks: s.breaks
    }));
    const buckets = buildCanonicalDailyBuckets(bucketInputs);

    const siteIds = [...new Set(buckets.map((b) => b.siteId))];
    const sites = siteIds.length > 0 ? await tx.workSite.findMany({ where: { id: { in: siteIds } }, select: { id: true, name: true } }) : [];
    const siteNameById = new Map(sites.map((s) => [s.id, s.name]));

    // §BF step 8 — batch id generated before CSV bytes, since it's embedded in every row.
    const batchId = randomUUID();
    const periodStartDate = formatDate(period.startDate);
    const periodEndDate = formatDate(period.endDate);

    interface RowRecord extends ExportRowSortKey {
      employeeNameSnapshot: string;
      timesheetVersionId: string;
      grossMinutes: number;
      paidBreakMinutes: number;
      unpaidBreakMinutes: number;
      workedMinutes: number;
      segmentCount: number;
    }

    const rowRecords: RowRecord[] = buckets.map((b) => {
      const emp = employeeById.get(b.employeeId)!;
      return {
        employeeId: b.employeeId,
        employeeNumberSnapshot: emp.employeeNumber,
        employeeNameSnapshot: `${emp.firstName} ${emp.lastName}`,
        siteId: b.siteId,
        siteNameSnapshot: siteNameById.get(b.siteId) ?? '',
        date: b.date,
        timesheetVersionId: b.timesheetVersionId!,
        grossMinutes: b.grossMinutes,
        paidBreakMinutes: b.paidBreakMinutes,
        unpaidBreakMinutes: b.unpaidBreakMinutes,
        workedMinutes: b.workedMinutes,
        segmentCount: b.segmentCount
      };
    });
    rowRecords.sort(compareExportRows);

    const csvRows = rowRecords.map((r) => [
      periodId,
      periodStartDate,
      periodEndDate,
      batchId,
      kind,
      r.employeeId,
      r.employeeNumberSnapshot,
      r.employeeNameSnapshot,
      r.siteId,
      r.siteNameSnapshot,
      r.date,
      r.timesheetVersionId,
      r.grossMinutes,
      r.paidBreakMinutes,
      r.unpaidBreakMinutes,
      r.workedMinutes,
      r.segmentCount
    ]);
    const content = buildCsvV1Content(csvRows);
    const fileHash = createHash('sha256').update(content).digest('hex');
    const fileSizeBytes = content.byteLength;
    const fileName = buildFileName(periodStartDate, periodEndDate, kind, batchId);
    const rowCount = rowRecords.length;

    let correctsBatchId: string | null = null;
    if (kind === 'CORRECTION') {
      const predecessor = await tx.exportBatch.findFirst({ where: { periodId }, orderBy: [{ createdAt: 'desc' }, { id: 'desc' }], select: { id: true } });
      if (!predecessor) {
        throw new Error(`EXPORT_INVARIANT_FAILURE: EXPORTED period ${periodId} has no predecessor ExportBatch for a CORRECTION`);
      }
      correctsBatchId = predecessor.id;
    }

    const createdBatch = await tx.exportBatch.create({
      data: { id: batchId, periodId, format: 'CSV_V1', kind, createdByUserId: actorUserId, correctsBatchId, fileName, fileHash, fileSizeBytes, rowCount, content: toPrismaBytes(content) }
    });

    if (rowRecords.length > 0) {
      await tx.exportItem.createMany({
        data: rowRecords.map((r) => ({
          exportBatchId: batchId,
          employeeId: r.employeeId,
          timesheetVersionId: r.timesheetVersionId,
          siteId: r.siteId,
          date: new Date(`${r.date}T00:00:00.000Z`),
          employeeNumberSnapshot: r.employeeNumberSnapshot,
          employeeNameSnapshot: r.employeeNameSnapshot,
          siteNameSnapshot: r.siteNameSnapshot,
          grossMinutes: r.grossMinutes,
          paidBreakMinutes: r.paidBreakMinutes,
          unpaidBreakMinutes: r.unpaidBreakMinutes,
          workedMinutes: r.workedMinutes,
          segmentCount: r.segmentCount
        }))
      });
    }

    if (kind === 'CORRECTION' && pendingCorrectionIds.length > 0) {
      await tx.correctionRequest.updateMany({ where: { id: { in: pendingCorrectionIds } }, data: { coveredByExportBatchId: batchId, pendingExport: false } });
    }

    let exportedAt = period.exportedAt;
    if (kind === 'FULL') {
      const updatedPeriod = await tx.payrollPeriod.update({ where: { id: periodId }, data: { status: 'EXPORTED', exportedAt: new Date() } });
      exportedAt = updatedPeriod.exportedAt;
    }

    const coveredCorrectionCount = pendingCorrectionIds.length;

    // §BL — allowed AuditEvent fields only. No CSV content, no employee names/numbers, no
    // individual ExportItem, no correction reason, no GPS/device/payload/request data.
    await createAuditEvent(tx, {
      actorUserId,
      eventType: 'EXPORT_CREATED',
      entityType: 'EXPORT_BATCH',
      entityId: batchId,
      requestId,
      beforeValue: null,
      afterValue: { exportBatchId: batchId, periodId, format: 'CSV_V1', kind, correctsBatchId, rowCount, fileSizeBytes, fileHash, coveredCorrectionCount }
    });

    return {
      batch: {
        id: batchId,
        periodId,
        format: 'CSV_V1',
        kind,
        correctsBatchId,
        fileName,
        fileHash,
        fileSizeBytes,
        rowCount,
        createdAt: createdBatch.createdAt.toISOString(),
        downloadUrl: `/api/admin/export-batches/${batchId}/download`
      },
      period: { id: periodId, status: 'EXPORTED', exportedAt: exportedAt!.toISOString() },
      coveredCorrectionCount
    };
  }, EXPORT_TX_OPTIONS);
}

