// docs/titanor-time/T8_REPORTS_DESIGN.md Addendum "T8.4B" — single owner of CSV_V1 generation,
// FULL/CORRECTION export-batch creation, and read access (list/detail/download). Every byte-format
// rule (§BG-BJ), population rule (§BA-BC), locking order (§BM), and audit/redaction rule (§BL/BN)
// documented there is implemented here, in one place, not scattered across route handlers.

// Deliberately NOT RepeatableRead (unlike the read-only T8.1-T8.3 report transactions, which never
// take a row lock or write). This transaction locks rows FOR UPDATE and then conditionally writes —
// the same shape as lib/periods.ts::lockPeriod and lib/corrections.ts::decideCorrection, both of
// which also run under Prisma/Postgres's plain default (READ COMMITTED), not RepeatableRead. Under
// RepeatableRead, a FOR UPDATE that blocks behind a concurrent writer and then unblocks against a
// row that writer just changed raises a real `40001 could not serialize access due to concurrent
// update` instead of just re-reading the fresh committed row — confirmed empirically by the two-
// concurrent-exporter tests (D37/D38) before this was found and fixed. READ COMMITTED is exactly
// the semantics this function's own "lock, then re-check the fresh state" steps (§BF) already
// assume.
const EXPORT_TX_OPTIONS = { maxWait: 10_000, timeout: 20_000 } as const;

const DEFAULT_PAGE_SIZE = 20;
const MAX_PAGE_SIZE = 100;

function formatDate(date: Date): string {
  return date.toISOString().slice(0, 10);
}

// ============================================================================
// §BG-BJ — CSV_V1 exact byte contract. Pure functions, no I/O.
// ============================================================================

const CSV_BOM = Buffer.from([0xef, 0xbb, 0xbf]);
const CRLF = '\r\n';

export const CSV_V1_COLUMNS = [
  'period_id',
  'period_start_date',
  'period_end_date',
  'export_batch_id',
  'export_kind',
  'employee_id',
  'employee_number',
  'employee_name',
  'site_id',
  'site_name',
  'date',
  'timesheet_version_id',
  'gross_minutes',
  'paid_break_minutes',
  'unpaid_break_minutes',
  'worked_minutes',
  'segment_count'
] as const;

// Indices of CSV_V1_COLUMNS that hold human-controlled text (employee_number, employee_name,
// site_name) — the only columns run through the formula-injection guard (§BI). UUID/date/integer/
// generated-metadata columns are never sanitized this way.
const HUMAN_TEXT_COLUMN_INDICES = new Set([6, 7, 9]);

// §BI — leading ASCII spaces only (not all whitespace) are skipped before checking the trigger
// character, because tab/CR/LF are themselves listed as distinct trigger characters, not absorbed
// into "leading whitespace".
const CSV_FORMULA_TRIGGER_RE = /^ *[=+\-@\t\r\n]/;

export function sanitizeHumanTextCell(value: string): string {
  return CSV_FORMULA_TRIGGER_RE.test(value) ? `'${value}` : value;
}

function escapeCell(value: string): string {
  return `"${value.replace(/"/g, '""')}"`;
}

function buildCsvRow(cells: readonly (string | number)[]): string {
  const escaped = cells.map((cell, index) => {
    const raw = String(cell);
    const sanitized = HUMAN_TEXT_COLUMN_INDICES.has(index) ? sanitizeHumanTextCell(raw) : raw;
    return escapeCell(sanitized);
  });
  return escaped.join(',') + CRLF;
}

/** Builds the exact CSV_V1 bytes — BOM + header + zero or more data rows, every row (including the last) CRLF-terminated. `rows` must already be in final, deterministic order (§BH) — this function does not sort. */
export function buildCsvV1Content(rows: readonly (readonly (string | number)[])[]): Buffer {
  const header = buildCsvRow(CSV_V1_COLUMNS);
  const body = rows.map((row) => buildCsvRow(row)).join('');
  return Buffer.concat([CSV_BOM, Buffer.from(header + body, 'utf8')]);
}

// Node's global Uint8Array typing (@types/node) widens `new Uint8Array(n)` to
// Uint8Array<ArrayBufferLike>; Prisma's generated Bytes field type wants the narrower
// Uint8Array<ArrayBuffer> specifically (same ecosystem type gap already documented in
// lib/idempotency.ts's encryptResponseBody — the underlying buffer genuinely is a plain
// ArrayBuffer here, never a SharedArrayBuffer).
function toPrismaBytes(buffer: Buffer): Uint8Array<ArrayBuffer> {
  const out = new Uint8Array(buffer.byteLength);
  out.set(buffer);
  return out as Uint8Array<ArrayBuffer>;
}

function buildFileName(startDate: string, endDate: string, kind: 'FULL' | 'CORRECTION', batchId: string): string {
  return `titanor-time_${startDate}_${endDate}_${kind === 'FULL' ? 'full' : 'correction'}_${batchId}.csv`;
}

// §BH — deterministic ordering. Plain code-point (UTF-16 code unit) comparison — never
// localeCompare/Intl, which is locale- and runtime-dependent.
function compareBinary(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

interface ExportRowSortKey {
  employeeNumberSnapshot: string;
  employeeId: string;
  date: string;
  siteNameSnapshot: string;
  siteId: string;
}

function compareExportRows(a: ExportRowSortKey, b: ExportRowSortKey): number {
  return (
    compareBinary(a.employeeNumberSnapshot, b.employeeNumberSnapshot) ||
    compareBinary(a.employeeId, b.employeeId) ||
    compareBinary(a.date, b.date) ||
    compareBinary(a.siteNameSnapshot, b.siteNameSnapshot) ||
    compareBinary(a.siteId, b.siteId)
  );
}

