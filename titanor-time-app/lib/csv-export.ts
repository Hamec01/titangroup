/** §BK GET /api/admin/export-batches/:batchId — metadata + covered correction ids + paginated ExportItem DTO. Never includes `content` or correction reason/payload. */
export async function getExportBatchDetail(batchId: string, pagination: { page: number; pageSize: number }): Promise<ExportBatchDetail | null> {
  const batch = await prisma.exportBatch.findUnique({ where: { id: batchId }, select: EXPORT_BATCH_SUMMARY_SELECT });
  if (!batch) {
    return null;
  }

  const [coveredCorrections, totalItems, items] = await Promise.all([
    prisma.correctionRequest.findMany({ where: { coveredByExportBatchId: batchId }, select: { id: true }, orderBy: { id: 'asc' } }),
    prisma.exportItem.count({ where: { exportBatchId: batchId } }),
    prisma.exportItem.findMany({
      where: { exportBatchId: batchId },
      orderBy: [{ employeeNumberSnapshot: 'asc' }, { employeeId: 'asc' }, { date: 'asc' }, { siteNameSnapshot: 'asc' }, { siteId: 'asc' }],
      skip: (pagination.page - 1) * pagination.pageSize,
      take: pagination.pageSize,
      select: {
        id: true,
        employeeId: true,
        employeeNumberSnapshot: true,
        employeeNameSnapshot: true,
        siteId: true,
        siteNameSnapshot: true,
        date: true,
        timesheetVersionId: true,
        grossMinutes: true,
        paidBreakMinutes: true,
        unpaidBreakMinutes: true,
        workedMinutes: true,
        segmentCount: true
      }
    })
  ]);

  return {
    batch: toSummaryDto(batch),
    coveredCorrectionIds: coveredCorrections.map((c) => c.id),
    coveredCorrectionCount: coveredCorrections.length,
    items: items.map((i) => ({ ...i, date: formatDate(i.date) })),
    page: pagination.page,
    pageSize: pagination.pageSize,
    totalItems,
    totalPages: Math.ceil(totalItems / pagination.pageSize)
  };
}

export interface ExportBatchDownload {
  fileName: string;
  fileHash: string;
  fileSizeBytes: number;
  content: Buffer;
}

/** §BK GET /api/admin/export-batches/:batchId/download — exact stored bytes, never reconstructed. */
export async function getExportBatchDownload(batchId: string): Promise<ExportBatchDownload | null> {
  const batch = await prisma.exportBatch.findUnique({ where: { id: batchId }, select: { fileName: true, fileHash: true, fileSizeBytes: true, content: true } });
  if (!batch) {
    return null;
  }
  return { fileName: batch.fileName, fileHash: batch.fileHash, fileSizeBytes: batch.fileSizeBytes, content: Buffer.from(batch.content) };
}
